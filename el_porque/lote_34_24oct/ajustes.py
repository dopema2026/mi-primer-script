def aplicar(shorts):
    for s in shorts:
        bl = list(s["bloques"])
        for idx, nuevo in REEMPLAZOS.get(s["slug"], {}).items():
            bl[idx] = nuevo
        n = len(bl)
        ins = [((n - 1) if i == -1 else i, k, (t, x)) for k, (i, t, x) in enumerate(EXTRAS.get(s["slug"], []))]
        for pos, _, b in sorted(ins, key=lambda e: (-e[0], -e[1])):
            bl.insert(pos, b)
        s["bloques"] = bl
    return shorts
